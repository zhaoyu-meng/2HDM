"""
Plot R1 field and create animation from simulation snapshots.

This script reads field data from files generated by the C++ simulation,
plots the R1 distribution at selected time steps, and creates a GIF animation
of the evolution. Additionally, it plots the global quantity (last column)
from the valsPerLoop file.
"""

import numpy as np
import matplotlib.pyplot as plt
import imageio
import os
import io

# Simulation parameters (must match the C++ simulation)
size = 128           # Grid size (nx = ny = 128)
dx = 0.5             # Grid spacing [1/m_h]
dt = 0.1             # Time step [1/(c m_h)]

def finalplot(time):
    """
    Plot the R1 field distribution at a given time step.

    Parameters
    ----------
    time : int
        Time step index (the file name contains this number).

    Returns
    -------
    matplotlib.figure.Figure or None
        The figure object if successful, otherwise None.
    """
    plot_s = 64  # Number of grid points to show in each direction (centered)

    fig, ax = plt.subplots(1, 1, figsize=(6, 5))

    try:
        # File name format: fields_timestep=<time>_2d_nx128_nt4800_seed79_2HDM.txt
        filename = f'Data/fields_timestep={time}_2d_nx128_nt4800_seed79_2HDM.txt'
        data = np.genfromtxt(filename, skip_header=1)

        # Physical coordinates
        x_min, x_max = -plot_s * dx, plot_s * dx
        y_min, y_max = -plot_s * dx, plot_s * dx

        # Extract R1 (second column, index 1) and reshape to 2D grid
        field = data[:size * size, 1].reshape((size, size))
        # Center the plot around the origin
        field_center = field[
            int(size/2 - plot_s):int(size/2 + plot_s),
            int(size/2 - plot_s):int(size/2 + plot_s)
        ]

        im = ax.imshow(field_center, cmap='seismic', aspect='auto',
                       vmin=-2.5, vmax=2.5,
                       extent=[x_min, x_max, y_min, y_max])
        plt.colorbar(im, ax=ax)
        # Optionally add labels and title (commented out for publication style)
        # ax.set_xlabel("x")
        # ax.set_ylabel("y")
        # ax.set_title(f'R1 distribution at t={time*dt:.2f}')

        plt.tight_layout()
        return fig

    except Exception as e:
        print(f"Error reading file {filename}: {e}")
        return None

def create_gif(start_time, end_time, time_step=10, gif_name='animation.gif'):
    """
    Create a GIF animation from a sequence of time steps.

    Parameters
    ----------
    start_time, end_time : int
        Time step indices for the first and last frame.
    time_step : int
        Step between frames.
    gif_name : str
        Output GIF file name.
    """
    images = []
    print(f"Creating GIF from time={start_time} to {end_time} with step={time_step}")

    # Create a directory for intermediate images (optional)
    if not os.path.exists('gif'):
        os.makedirs('gif')

    for t in range(start_time, end_time + 1, time_step):
        print(f"Processing time step: {t}")
        fig = finalplot(t)
        if fig is not None:
            # Save the figure to a memory buffer as PNG
            buf = io.BytesIO()
            fig.savefig(buf, format='png', dpi=100)
            buf.seek(0)
            image = imageio.imread(buf)
            images.append(image)
            plt.close(fig)
            buf.close()

    if images:
        print(f"Saving GIF with {len(images)} frames...")
        imageio.mimsave(gif_name, images, fps=20, loop=0)
        print(f"GIF saved as {gif_name}")
    else:
        print("No images to save.")

def wall_plot(vals_file):
    if os.path.exists(vals_file):
        data_vals = np.genfromtxt(vals_file, skip_header=1)
        # If data_vals is 1D (only one column), reshape to 2D
        if data_vals.ndim == 1:
            data_vals = data_vals.reshape(-1, 1)
        # The last column is the quantity of interest (e.g., ADW_Full)
        y = data_vals[:, -1]
        # Time axis: each row corresponds to one time step, starting from 0
        t = np.arange(len(y)) * dt
        plt.figure()
        plt.plot(t, y, linewidth=1)
        plt.xlabel('Time')
        plt.ylabel('Wall length')
        plt.ylim(0,300)
        # plt.title('Evolution of wall area')
        # plt.grid(True)
        plt.show()
    else:
        print(f"File {vals_file} not found. Skipping additional plot.")

